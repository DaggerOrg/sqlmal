var plainIdent = regexp.MustCompile(`^[a-z_][a-z0-9_]*$`)

var reserved = map[string]bool{
	"all": true, "analyse": true, "analyze": true, "and": true, "any": true, "array": true, "as": true, "asc": true, "both": true,
	"case": true, "cast": true, "check": true, "collate": true, "column": true, "constraint": true, "create": true, "current_date": true,
	"current_user": true, "default": true, "desc": true, "distinct": true, "do": true, "else": true, "end": true, "except": true,
	"false": true, "fetch": true, "for": true, "foreign": true, "from": true, "grant": true, "group": true, "having": true, "in": true,
	"initially": true, "intersect": true, "into": true, "leading": true, "limit": true, "not": true, "null": true, "offset": true,
	"on": true, "only": true, "or": true, "order": true, "placing": true, "primary": true, "references": true, "returning": true,
	"select": true, "session_user": true, "some": true, "symmetric": true, "table": true, "then": true, "to": true, "trailing": true,
	"true": true, "union": true, "unique": true, "user": true, "using": true, "variadic": true, "when": true, "where": true, "window": true, "with": true,
}

// Ident quotes an identifier only when it has to be.
func Ident(s string) string {
	if plainIdent.MatchString(s) && !reserved[s] {
		return s
	}
	return `"` + strings.ReplaceAll(s, `"`, `""`) + `"`
}

func idents(cols []string) string {
	q := make([]string, len(cols))
	for i, c := range cols {
		q[i] = Ident(c)
	}
	return strings.Join(q, ", ")
}

// Script is generated SQL plus anything the author must check by hand.
type Script struct {
	SQL      string   `json:"sql"`
	Warnings []string `json:"warnings"`
}

var serialDefault = regexp.MustCompile(`^nextval\('(?:[A-Za-z_][A-Za-z0-9_]*\.)?"?([^'"]+)"?'::regclass\)$`)

// columnDef writes one column. A column whose default is its own sequence is
// written as serial, because the sequence does not exist yet when the table is created.
func columnDef(table string, c introspect.Column) string {
	typ, def := c.Type, c.Default
	if m := serialDefault.FindStringSubmatch(def); m != nil && m[1] == table+"_"+c.Name+"_seq" {
		switch c.Type {
		case "integer":
			typ, def = "serial", ""
		case "bigint":
			typ, def = "bigserial", ""
		case "smallint":
			typ, def = "smallserial", ""
		}
	}
	s := Ident(c.Name) + " " + typ
	switch c.Identity {
	case "always":
		s += " GENERATED ALWAYS AS IDENTITY"
	case "by default":
		s += " GENERATED BY DEFAULT AS IDENTITY"
	}
	if c.Generated != "" {
		s += " GENERATED ALWAYS AS (" + c.Generated + ") STORED"
	}
	if def != "" {
		s += " DEFAULT " + def
	}
	if c.NotNull && !strings.HasPrefix(typ, "serial") && !strings.HasPrefix(typ, "bigserial") && !strings.HasPrefix(typ, "smallserial") {
		s += " NOT NULL"
	}
	return s
}

func fkClause(f introspect.ForeignKey) string {
	s := fmt.Sprintf("FOREIGN KEY (%s) REFERENCES %s (%s)", idents(f.Columns), Ident(f.RefTable), idents(f.RefColumns))
	if f.OnDelete != "" && f.OnDelete != "NO ACTION" {
		s += " ON DELETE " + f.OnDelete
	}
	if f.OnUpdate != "" && f.OnUpdate != "NO ACTION" {
		s += " ON UPDATE " + f.OnUpdate
	}
	return s
}

func createIndexSQL(i introspect.Index) string {
	// pg_get_indexdef qualifies the table with its schema, which a migration should not hard-code.
	return strings.Replace(i.Def, " ON public.", " ON ", 1) + ";"
}

// Generate writes the SQL that turns from into to. Review it before running:
// a rename looks like a drop and an add, and a type change may need a USING clause.
func Generate(from, to introspect.Schema) Script {
	var st []string
	var warn []string
	add := func(s string) { st = append(st, s) }
	ta, tb := tableMap(from), tableMap(to)

	// Enums first: tables may use them.
	ea := enumMap(from)
	for _, e := range to.Enums {
		old, ok := ea[e.Name]
		if !ok {
			labels := make([]string, len(e.Labels))
			for i, l := range e.Labels {
				labels[i] = "'" + strings.ReplaceAll(l, "'", "''") + "'"
			}
			add(fmt.Sprintf("CREATE TYPE %s AS ENUM (%s);", Ident(e.Name), strings.Join(labels, ", ")))
			continue
		}
		have := map[string]bool{}
		for _, l := range old.Labels {
			have[l] = true
		}
		for _, l := range e.Labels {
			if !have[l] {
				add(fmt.Sprintf("ALTER TYPE %s ADD VALUE '%s';", Ident(e.Name), strings.ReplaceAll(l, "'", "''")))
				warn = append(warn, fmt.Sprintf("New enum value %q on %s cannot be used in the same transaction that adds it.", l, e.Name))
			}
		}
	}

	// Tear down what is going away, in an order that never leaves a dangling reference.
	var dropTables []string
	for _, name := range sortedNames(ta, tb) {
		x, inA := ta[name]
		y, inB := tb[name]
		if !inA {
			continue
		}
		if !inB {
			dropTables = append(dropTables, name)
			continue
		}
		fy := map[string]introspect.ForeignKey{}
		for _, f := range y.ForeignKeys {
			fy[f.Name] = f
		}
		for _, f := range x.ForeignKeys {
			if g, ok := fy[f.Name]; !ok || fkClause(f) != fkClause(g) {
				add(fmt.Sprintf("ALTER TABLE %s DROP CONSTRAINT %s;", Ident(name), Ident(f.Name)))
			}
		}
		cy := map[string]introspect.Check{}
		for _, c := range y.Checks {
			cy[c.Name] = c
		}
		for _, c := range x.Checks {
			if g, ok := cy[c.Name]; !ok || g.Expr != c.Expr {
				add(fmt.Sprintf("ALTER TABLE %s DROP CONSTRAINT %s;", Ident(name), Ident(c.Name)))
			}
		}
		uy := map[string]introspect.Unique{}
		for _, u := range y.Uniques {
			uy[u.Name] = u
		}
		for _, u := range x.Uniques {
			if g, ok := uy[u.Name]; !ok || strings.Join(g.Columns, ",") != strings.Join(u.Columns, ",") {
				add(fmt.Sprintf("ALTER TABLE %s DROP CONSTRAINT %s;", Ident(name), Ident(u.Name)))
			}
		}
		iy := indexMap(y)
		for _, i := range indexMap(x) {
			if g, ok := iy[i.Name]; !ok || g.Def != i.Def {
				add(fmt.Sprintf("DROP INDEX %s;", Ident(i.Name)))
			}
		}
		if strings.Join(x.PrimaryKey, ",") != strings.Join(y.PrimaryKey, ",") && x.PrimaryKeyName != "" {
			add(fmt.Sprintf("ALTER TABLE %s DROP CONSTRAINT %s;", Ident(name), Ident(x.PrimaryKeyName)))
		}
	}
	if len(dropTables) > 0 {
		q := make([]string, len(dropTables))
		for i, t := range dropTables {
			q[i] = Ident(t)
		}
		add(fmt.Sprintf("DROP TABLE %s;", strings.Join(q, ", ")))
		warn = append(warn, "Dropping "+strings.Join(dropTables, ", ")+" deletes its data permanently.")
	}
	for _, e := range from.Enums {
		if _, ok := enumMap(to)[e.Name]; !ok {
			add(fmt.Sprintf("DROP TYPE %s;", Ident(e.Name)))
		}
	}

	// New tables: columns and keys first, foreign keys last so creation order never matters.
	var lateFKs []string
	for _, name := range sortedNames(ta, tb) {
		y, inB := tb[name]
		if _, inA := ta[name]; inA || !inB {
			continue
		}
		var lines []string
		for _, c := range y.Columns {
			lines = append(lines, "    "+columnDef(name, c))
		}
		if len(y.PrimaryKey) > 0 {
			lines = append(lines, fmt.Sprintf("    CONSTRAINT %s PRIMARY KEY (%s)", Ident(y.PrimaryKeyName), idents(y.PrimaryKey)))
		}
		for _, u := range y.Uniques {
			lines = append(lines, fmt.Sprintf("    CONSTRAINT %s UNIQUE (%s)", Ident(u.Name), idents(u.Columns)))
		}
		for _, c := range y.Checks {
			lines = append(lines, fmt.Sprintf("    CONSTRAINT %s CHECK %s", Ident(c.Name), c.Expr))
		}
		if y.Partitioned {
			warn = append(warn, fmt.Sprintf("%s is partitioned; its PARTITION BY clause and partitions are not generated.", name))
		}
		add(fmt.Sprintf("CREATE TABLE %s (\n%s\n);", Ident(name), strings.Join(lines, ",\n")))
		for _, i := range indexMap(y) {
			add(createIndexSQL(i))
		}
		for _, f := range y.ForeignKeys {
			lateFKs = append(lateFKs, fmt.Sprintf("ALTER TABLE %s ADD CONSTRAINT %s %s;", Ident(name), Ident(f.Name), fkClause(f)))
		}
	}

	// Existing tables.
	for _, name := range sortedNames(ta, tb) {
		x, inA := ta[name]
		y, inB := tb[name]
		if !inA || !inB {
			continue
		}
		cx := colMap(x)
		cy := colMap(y)
		for _, c := range x.Columns {
			if _, ok := cy[c.Name]; !ok {
				add(fmt.Sprintf("ALTER TABLE %s DROP COLUMN %s;", Ident(name), Ident(c.Name)))
				warn = append(warn, fmt.Sprintf("Dropping column %s.%s deletes its data permanently.", name, c.Name))
			}
		}
		for _, c := range y.Columns {
			old, ok := cx[c.Name]
			if !ok {
				add(fmt.Sprintf("ALTER TABLE %s ADD COLUMN %s;", Ident(name), columnDef(name, c)))
				if c.NotNull && c.Default == "" && c.Identity == "" && !strings.Contains(columnDef(name, c), "serial") {
					warn = append(warn, fmt.Sprintf("%s.%s is NOT NULL with no default: adding it fails if the table has rows.", name, c.Name))
				}
				continue
			}
			col := Ident(c.Name)
			if old.Type != c.Type {
				add(fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s TYPE %s USING %s::%s;", Ident(name), col, c.Type, col, c.Type))
				warn = append(warn, fmt.Sprintf("Changing %s.%s from %s to %s may rewrite the table and needs a USING expression that suits your data.", name, c.Name, old.Type, c.Type))
			}
			if old.Default != c.Default && c.Identity == "" {
				if c.Default == "" {
					add(fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s DROP DEFAULT;", Ident(name), col))
				} else {
					add(fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s SET DEFAULT %s;", Ident(name), col, c.Default))
				}
			}
			if old.NotNull != c.NotNull {
				if c.NotNull {
					add(fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s SET NOT NULL;", Ident(name), col))
				} else {
					add(fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s DROP NOT NULL;", Ident(name), col))
				}
			}
			if old.Identity != c.Identity || old.Generated != c.Generated {
				warn = append(warn, fmt.Sprintf("%s.%s changed identity or generated expression: write this change by hand.", name, c.Name))
			}
		}
		if strings.Join(x.PrimaryKey, ",") != strings.Join(y.PrimaryKey, ",") && len(y.PrimaryKey) > 0 {
			add(fmt.Sprintf("ALTER TABLE %s ADD CONSTRAINT %s PRIMARY KEY (%s);", Ident(name), Ident(y.PrimaryKeyName), idents(y.PrimaryKey)))
		}
		ux := map[string]introspect.Unique{}
		for _, u := range x.Uniques {
			ux[u.Name] = u
		}
		for _, u := range y.Uniques {
			if g, ok := ux[u.Name]; !ok || strings.Join(g.Columns, ",") != strings.Join(u.Columns, ",") {
				add(fmt.Sprintf("ALTER TABLE %s ADD CONSTRAINT %s UNIQUE (%s);", Ident(name), Ident(u.Name), idents(u.Columns)))
			}
		}
		ckx := map[string]introspect.Check{}
		for _, c := range x.Checks {
			ckx[c.Name] = c
		}
		for _, c := range y.Checks {
			if g, ok := ckx[c.Name]; !ok || g.Expr != c.Expr {
				add(fmt.Sprintf("ALTER TABLE %s ADD CONSTRAINT %s CHECK %s;", Ident(name), Ident(c.Name), c.Expr))
			}
		}
		ix := indexMap(x)
		for _, i := range indexMap(y) {
			if g, ok := ix[i.Name]; !ok || g.Def != i.Def {
				add(createIndexSQL(i))
			}
		}
		fx := map[string]introspect.ForeignKey{}
		for _, f := range x.ForeignKeys {
			fx[f.Name] = f
		}
		for _, f := range y.ForeignKeys {
			if g, ok := fx[f.Name]; !ok || fkClause(g) != fkClause(f) {
				lateFKs = append(lateFKs, fmt.Sprintf("ALTER TABLE %s ADD CONSTRAINT %s %s;", Ident(name), Ident(f.Name), fkClause(f)))
			}
		}
	}
	st = append(st, lateFKs...)
	if len(st) == 0 {
		return Script{SQL: "", Warnings: []string{}}
	}
	if len(warn) == 0 {
		warn = []string{}
	}
	return Script{SQL: strings.Join(st, "\n\n") + "\n", Warnings: warn}
}
