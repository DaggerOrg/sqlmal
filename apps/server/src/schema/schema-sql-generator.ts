import type {
  CheckConstraint,
  Column,
  DatabaseSchema,
  ForeignKey,
  GeneratedSql,
  Index,
  Table,
  UniqueConstraint,
} from '@sqlmal/contracts';

import { quoteIdentifier, quoteIdentifiers, quoteLiteral } from '../sql/sql-identifier';
import { indexByName, listPlainIndexes, listSortedNames } from './schema-comparison';

const SERIAL_DEFAULT_PATTERN = /^nextval\('(?:[A-Za-z_][A-Za-z0-9_]*\.)?"?([^'"]+)"?'::regclass\)$/;
const SERIAL_TYPES_BY_INTEGER_TYPE: Record<string, string> = {
  integer: 'serial',
  bigint: 'bigserial',
  smallint: 'smallserial',
};

/**
 * Writes one column. A column whose default is its own sequence is written as serial,
 * because the sequence does not exist yet when the table is created.
 */
function writeColumnDefinition(tableName: string, column: Column): string {
  let type = column.type;
  let defaultExpression = column.defaultExpression ?? '';
  const serialDefault = SERIAL_DEFAULT_PATTERN.exec(defaultExpression);
  if (serialDefault !== null && serialDefault[1] === `${tableName}_${column.name}_seq`) {
    const serialType = SERIAL_TYPES_BY_INTEGER_TYPE[column.type];
    if (serialType !== undefined) {
      type = serialType;
      defaultExpression = '';
    }
  }
  let definition = `${quoteIdentifier(column.name)} ${type}`;
  if (column.identity === 'always') {
    definition += ' GENERATED ALWAYS AS IDENTITY';
  } else if (column.identity === 'by default') {
    definition += ' GENERATED BY DEFAULT AS IDENTITY';
  }
  if (column.generatedExpression !== undefined && column.generatedExpression !== '') {
    definition += ` GENERATED ALWAYS AS (${column.generatedExpression}) STORED`;
  }
  if (defaultExpression !== '') {
    definition += ` DEFAULT ${defaultExpression}`;
  }
  const isSerial = type.startsWith('serial') || type.startsWith('bigserial') || type.startsWith('smallserial');
  if (column.isNotNull && !isSerial) {
    definition += ' NOT NULL';
  }
  return definition;
}

function writeForeignKeyClause(foreignKey: ForeignKey): string {
  let clause = `FOREIGN KEY (${quoteIdentifiers(foreignKey.columns)}) REFERENCES ${quoteIdentifier(foreignKey.referencedTable)} (${quoteIdentifiers(foreignKey.referencedColumns)})`;
  if (foreignKey.onDelete !== 'NO ACTION') {
    clause += ` ON DELETE ${foreignKey.onDelete}`;
  }
  if (foreignKey.onUpdate !== 'NO ACTION') {
    clause += ` ON UPDATE ${foreignKey.onUpdate}`;
  }
  return clause;
}

/** pg_get_indexdef qualifies the table with its schema, which a migration should not hard-code. */
function writeCreateIndex(index: Index): string {
  return `${index.definition.replace(' ON public.', ' ON ')};`;
}

function haveSameColumns(left: UniqueConstraint, right: UniqueConstraint): boolean {
  return left.columns.join(',') === right.columns.join(',');
}

/**
 * Writes the SQL that turns `from` into `to`. Review it before running: a rename looks like a
 * drop and an add, and a type change may need a USING clause.
 */
export function generateSchemaSql(from: DatabaseSchema, to: DatabaseSchema): GeneratedSql {
  const statements: string[] = [];
  const warnings: string[] = [];
  const tablesBefore = indexByName<Table>(from.tables);
  const tablesAfter = indexByName<Table>(to.tables);
  const tableNames = listSortedNames(tablesBefore, tablesAfter);

  // Enums first: tables may use them.
  const enumsBefore = indexByName(from.enums);
  const enumsAfter = indexByName(to.enums);
  for (const enumType of to.enums) {
    const previous = enumsBefore.get(enumType.name);
    if (previous === undefined) {
      statements.push(
        `CREATE TYPE ${quoteIdentifier(enumType.name)} AS ENUM (${enumType.labels.map(quoteLiteral).join(', ')});`,
      );
      continue;
    }
    const previousLabels = new Set(previous.labels);
    for (const label of enumType.labels) {
      if (!previousLabels.has(label)) {
        statements.push(`ALTER TYPE ${quoteIdentifier(enumType.name)} ADD VALUE ${quoteLiteral(label)};`);
        warnings.push(
          `New enum value ${JSON.stringify(label)} on ${enumType.name} cannot be used in the same transaction that adds it.`,
        );
      }
    }
  }

  // Tear down what is going away, in an order that never leaves a dangling reference.
  const droppedTableNames: string[] = [];
  for (const tableName of tableNames) {
    const previous = tablesBefore.get(tableName);
    const next = tablesAfter.get(tableName);
    if (previous === undefined) {
      continue;
    }
    if (next === undefined) {
      droppedTableNames.push(tableName);
      continue;
    }
    const table = quoteIdentifier(tableName);
    const nextForeignKeys = indexByName<ForeignKey>(next.foreignKeys);
    for (const foreignKey of previous.foreignKeys) {
      const replacement = nextForeignKeys.get(foreignKey.name);
      if (replacement === undefined || writeForeignKeyClause(foreignKey) !== writeForeignKeyClause(replacement)) {
        statements.push(`ALTER TABLE ${table} DROP CONSTRAINT ${quoteIdentifier(foreignKey.name)};`);
      }
    }
    const nextChecks = indexByName<CheckConstraint>(next.checkConstraints);
    for (const check of previous.checkConstraints) {
      const replacement = nextChecks.get(check.name);
      if (replacement === undefined || replacement.expression !== check.expression) {
        statements.push(`ALTER TABLE ${table} DROP CONSTRAINT ${quoteIdentifier(check.name)};`);
      }
    }
    const nextUniques = indexByName<UniqueConstraint>(next.uniqueConstraints);
    for (const unique of previous.uniqueConstraints) {
      const replacement = nextUniques.get(unique.name);
      if (replacement === undefined || !haveSameColumns(replacement, unique)) {
        statements.push(`ALTER TABLE ${table} DROP CONSTRAINT ${quoteIdentifier(unique.name)};`);
      }
    }
    const nextIndexes = indexByName(listPlainIndexes(next));
    for (const index of listPlainIndexes(previous)) {
      const replacement = nextIndexes.get(index.name);
      if (replacement === undefined || replacement.definition !== index.definition) {
        statements.push(`DROP INDEX ${quoteIdentifier(index.name)};`);
      }
    }
    const previousPrimaryKeyName = previous.primaryKeyName ?? '';
    if (previous.primaryKey.join(',') !== next.primaryKey.join(',') && previousPrimaryKeyName !== '') {
      statements.push(`ALTER TABLE ${table} DROP CONSTRAINT ${quoteIdentifier(previousPrimaryKeyName)};`);
    }
  }
  if (droppedTableNames.length > 0) {
    statements.push(`DROP TABLE ${quoteIdentifiers(droppedTableNames)};`);
    warnings.push(`Dropping ${droppedTableNames.join(', ')} deletes its data permanently.`);
  }
  for (const enumType of from.enums) {
    if (!enumsAfter.has(enumType.name)) {
      statements.push(`DROP TYPE ${quoteIdentifier(enumType.name)};`);
    }
  }

  // New tables: columns and keys first, foreign keys last so creation order never matters.
  const deferredForeignKeys: string[] = [];
  for (const tableName of tableNames) {
    const next = tablesAfter.get(tableName);
    if (tablesBefore.has(tableName) || next === undefined) {
      continue;
    }
    const lines = next.columns.map((column) => `    ${writeColumnDefinition(tableName, column)}`);
    if (next.primaryKey.length > 0) {
      lines.push(
        `    CONSTRAINT ${quoteIdentifier(next.primaryKeyName ?? '')} PRIMARY KEY (${quoteIdentifiers(next.primaryKey)})`,
      );
    }
    for (const unique of next.uniqueConstraints) {
      lines.push(`    CONSTRAINT ${quoteIdentifier(unique.name)} UNIQUE (${quoteIdentifiers(unique.columns)})`);
    }
    for (const check of next.checkConstraints) {
      lines.push(`    CONSTRAINT ${quoteIdentifier(check.name)} CHECK ${check.expression}`);
    }
    if (next.isPartitioned) {
      warnings.push(`${tableName} is partitioned; its PARTITION BY clause and partitions are not generated.`);
    }
    statements.push(`CREATE TABLE ${quoteIdentifier(tableName)} (\n${lines.join(',\n')}\n);`);
    for (const index of listPlainIndexes(next)) {
      statements.push(writeCreateIndex(index));
    }
    for (const foreignKey of next.foreignKeys) {
      deferredForeignKeys.push(
        `ALTER TABLE ${quoteIdentifier(tableName)} ADD CONSTRAINT ${quoteIdentifier(foreignKey.name)} ${writeForeignKeyClause(foreignKey)};`,
      );
    }
  }

  // Existing tables.
  for (const tableName of tableNames) {
    const previous = tablesBefore.get(tableName);
    const next = tablesAfter.get(tableName);
    if (previous === undefined || next === undefined) {
      continue;
    }
    const table = quoteIdentifier(tableName);
    const previousColumns = indexByName(previous.columns);
    const nextColumns = indexByName(next.columns);
    for (const column of previous.columns) {
      if (!nextColumns.has(column.name)) {
        statements.push(`ALTER TABLE ${table} DROP COLUMN ${quoteIdentifier(column.name)};`);
        warnings.push(`Dropping column ${tableName}.${column.name} deletes its data permanently.`);
      }
    }
    for (const column of next.columns) {
      const old = previousColumns.get(column.name);
      if (old === undefined) {
        const definition = writeColumnDefinition(tableName, column);
        statements.push(`ALTER TABLE ${table} ADD COLUMN ${definition};`);
        const hasDefault = (column.defaultExpression ?? '') !== '';
        const hasIdentity = (column.identity ?? '') !== '';
        if (column.isNotNull && !hasDefault && !hasIdentity && !definition.includes('serial')) {
          warnings.push(
            `${tableName}.${column.name} is NOT NULL with no default: adding it fails if the table has rows.`,
          );
        }
        continue;
      }
      const columnName = quoteIdentifier(column.name);
      if (old.type !== column.type) {
        statements.push(
          `ALTER TABLE ${table} ALTER COLUMN ${columnName} TYPE ${column.type} USING ${columnName}::${column.type};`,
        );
        warnings.push(
          `Changing ${tableName}.${column.name} from ${old.type} to ${column.type} may rewrite the table and needs a USING expression that suits your data.`,
        );
      }
      const oldDefault = old.defaultExpression ?? '';
      const newDefault = column.defaultExpression ?? '';
      if (oldDefault !== newDefault && (column.identity ?? '') === '') {
        statements.push(
          newDefault === ''
            ? `ALTER TABLE ${table} ALTER COLUMN ${columnName} DROP DEFAULT;`
            : `ALTER TABLE ${table} ALTER COLUMN ${columnName} SET DEFAULT ${newDefault};`,
        );
      }
      if (old.isNotNull !== column.isNotNull) {
        statements.push(
          `ALTER TABLE ${table} ALTER COLUMN ${columnName} ${column.isNotNull ? 'SET' : 'DROP'} NOT NULL;`,
        );
      }
      if (
        (old.identity ?? '') !== (column.identity ?? '') ||
        (old.generatedExpression ?? '') !== (column.generatedExpression ?? '')
      ) {
        warnings.push(
          `${tableName}.${column.name} changed identity or generated expression: write this change by hand.`,
        );
      }
    }
    if (previous.primaryKey.join(',') !== next.primaryKey.join(',') && next.primaryKey.length > 0) {
      statements.push(
        `ALTER TABLE ${table} ADD CONSTRAINT ${quoteIdentifier(next.primaryKeyName ?? '')} PRIMARY KEY (${quoteIdentifiers(next.primaryKey)});`,
      );
    }
    const previousUniques = indexByName<UniqueConstraint>(previous.uniqueConstraints);
    for (const unique of next.uniqueConstraints) {
      const old = previousUniques.get(unique.name);
      if (old === undefined || !haveSameColumns(old, unique)) {
        statements.push(
          `ALTER TABLE ${table} ADD CONSTRAINT ${quoteIdentifier(unique.name)} UNIQUE (${quoteIdentifiers(unique.columns)});`,
        );
      }
    }
    const previousChecks = indexByName<CheckConstraint>(previous.checkConstraints);
    for (const check of next.checkConstraints) {
      const old = previousChecks.get(check.name);
      if (old === undefined || old.expression !== check.expression) {
        statements.push(`ALTER TABLE ${table} ADD CONSTRAINT ${quoteIdentifier(check.name)} CHECK ${check.expression};`);
      }
    }
    const previousIndexes = indexByName(listPlainIndexes(previous));
    for (const index of listPlainIndexes(next)) {
      const old = previousIndexes.get(index.name);
      if (old === undefined || old.definition !== index.definition) {
        statements.push(writeCreateIndex(index));
      }
    }
    const previousForeignKeys = indexByName<ForeignKey>(previous.foreignKeys);
    for (const foreignKey of next.foreignKeys) {
      const old = previousForeignKeys.get(foreignKey.name);
      if (old === undefined || writeForeignKeyClause(old) !== writeForeignKeyClause(foreignKey)) {
        deferredForeignKeys.push(
          `ALTER TABLE ${table} ADD CONSTRAINT ${quoteIdentifier(foreignKey.name)} ${writeForeignKeyClause(foreignKey)};`,
        );
      }
    }
  }
  statements.push(...deferredForeignKeys);
  if (statements.length === 0) {
    return { sql: '', warnings: [] };
  }
  return { sql: `${statements.join('\n\n')}\n`, warnings };
}
